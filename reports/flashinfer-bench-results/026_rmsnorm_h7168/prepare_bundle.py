"""Materialize the official dataset row and the exact archive entry for local evaluation."""

import argparse
import json
from pathlib import Path

import pyarrow.parquet as pq


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output_dir", type=Path)
    repo = Path(__file__).resolve().parents[3]
    parser.add_argument(
        "--parquet",
        type=Path,
        default=repo / ".artifacts/sol-data/FlashInfer-Bench.parquet",
    )
    args = parser.parse_args()
    name = "026_rmsnorm_h7168"
    source = repo / "flashinfer-bench" / name / "submission.py"
    [record] = pq.read_table(args.parquet, filters=[("name", "=", name)]).to_pylist()
    workloads = json.loads(record.pop("workloads"))
    expected_batches = [1, 7, 18, 32, 64, 539, 11949, 14521]
    if sorted(row["axes"]["batch_size"] for row in workloads) != expected_batches:
        raise ValueError("Unexpected official workloads in the Parquet row")
    if len({row["uuid"] for row in workloads}) != len(expected_batches):
        raise ValueError("Unexpected official workload UUIDs")
    if any(item["type"] != "random" for row in workloads for item in row["inputs"].values()):
        raise ValueError("This benchmark expects inputs generated by the evaluator")

    definition = {
        key: json.loads(value) if key in {"axes", "inputs", "outputs"} else value
        for key, value in record.items()
        if value is not None and value != ""
    }
    bundle = {
        "name": name,
        "definition": name,
        "author": "RSI-Kernel-Tune",
        "spec": {
            "languages": ["triton"],
            "entry_point": "submission.py::run",
            "target_hardware": ["B200", "LOCAL"],
            "destination_passing_style": True,
            "dependencies": ["triton"],
        },
        "sources": [{"path": "submission.py", "content": source.read_bytes().decode("utf-8")}],
    }
    config = {
        "warmup_runs": 10,
        "iterations": 50,
        "seed": 200,
        "lock_clocks": False,
        "benchmark_reference": False,
    }
    dest = args.output_dir
    dest.mkdir(parents=True, exist_ok=True)
    for filename, value in (
        ("definition.json", definition),
        ("config.json", config),
        ("solution.json", bundle),
    ):
        (dest / filename).write_text(json.dumps(value, indent=2) + "\n")
    (dest / "workload.jsonl").write_text("".join(json.dumps(row) + "\n" for row in workloads))


if __name__ == "__main__":
    main()
