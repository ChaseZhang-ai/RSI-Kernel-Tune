@dataclass
class RewriteReport:
    candidates: list[Candidate] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    attempts: int = 0


def _parse_json(text: str) -> dict:
    decoder = json.JSONDecoder()
    for match in re.finditer(r"\{", text):
        try:
            obj, _ = decoder.raw_decode(text[match.start():])
        except ValueError:
            continue
        if isinstance(obj, dict) and isinstance(obj.get("candidates"), list):
            return obj
    raise ValueError("the answer holds no JSON object with a 'candidates' list")


def _validate_rewrites(payload: dict, definition: dict | None = None) -> tuple[list[Candidate], list[str]]:
    good: list[Candidate] = []
    errors: list[str] = []
    seen: set[str] = set()
    inputs = outputs = None
    if definition is not None:
        input_names, output_names = signature(definition)
        inputs, outputs = len(input_names), len(output_names)
    for i, row in enumerate(payload.get("candidates") or []):
        if not isinstance(row, dict):
            errors.append(f"candidate {i}: not an object")
            continue
        name = str(row.get("name") or f"rewrite-{i + 1}")
        source = row.get("source")
        if not isinstance(source, str) or not source.strip():
            errors.append(f"{name}: no source")
            continue
        try:
            nz.parse(source, f"{name}.py")
            if "run" not in nz.top_level_functions(source):
                raise nz.NormalizeError("no top-level run")
            problems = nz.static_rules_check(source, require_arch_provenance=nz.compiles_cuda(source))
        except nz.NormalizeError as exc:
            errors.append(f"{name}: {exc}")
            continue
        if problems:
            errors.append(f"{name}: " + "; ".join(problems))
            continue
        problems = warmstart_violations(source, n_inputs=inputs, n_outputs=outputs)
        if problems:
            errors.append(f"{name}: warmstart.validate: " + "; ".join(problems))
            continue
        safe = re.sub(r"[^0-9A-Za-z_.-]+", "-", name).strip("-_.") or f"rewrite-{i + 1}"
        if safe in seen:
            safe = f"{safe}-{i + 1}"
        seen.add(safe)
        good.append(Candidate(name=safe, source=source, uses=str(row.get("uses") or ""),
                              kind="rewrite", precision="default",
                              preconditions=[str(x) for x in (row.get("preconditions") or [])],
                              notes=[str(x) for x in (row.get("notes") or [])]))
    return good, errors


def rewrite_candidates(definition: dict, backend, *, prompt_path: str | Path | None = None,
                       definition_path: str | Path | None = None,
                       reference_path: str | Path | None = None,
                       target_profile: str | Path | None = None,
                       retries: int = 1) -> RewriteReport:
    """Ask one teacher turn (fresh context per turn) for library-operator candidates.

    The prompt is ``meta/baseline_rewrite_prompt.md``; the answer must be JSON only. A
    validation failure is fed back once (a new turn) and the report records both attempts.
    """
    from forgekernel.paths import repo_root
    from forgekernel.klib.ingest import render_prompt

    prompt_file = Path(prompt_path) if prompt_path else repo_root() / REWRITE_PROMPT_FILE
    template = prompt_file.read_text(encoding="utf-8")
    report = RewriteReport()
    feedback = ""
    last_error = ""
    for attempt in range(1, max(1, int(retries)) + 2):
        report.attempts = attempt
        bindings = {
            "DEFINITION_PATH": str(definition_path) if definition_path else "(inline)",
            "REFERENCE_PATH": str(reference_path) if reference_path else "(inline)",
            "TARGET_PROFILE_PATH": str(target_profile) if target_profile else "(none)",
            "FEEDBACK": feedback or "(none)",
        }
        prompt = render_prompt(template, bindings)
        if re.search(r"\{[A-Z][A-Z0-9_]*\}", prompt):
            raise ValueError(f"{prompt_file}: unreplaced placeholders in the prompt")
        try:
            answer = backend.run_agent(prompt, role="teacher")
        except Exception as exc:  # noqa: BLE001 -- a failed turn is reported, not raised
            last_error = f"agent turn failed: {type(exc).__name__}: {exc}"
            report.errors.append(last_error)
            feedback = last_error
            continue
        try:
            payload = _parse_json(answer)
        except ValueError as exc:
            last_error = str(exc)
            report.errors.append(last_error)
            feedback = f"the previous answer was rejected: {last_error}"
            continue
        good, errors = _validate_rewrites(payload, definition)
        report.errors.extend(errors)
        if good:
            report.candidates = good
            return report
        last_error = "; ".join(errors) or "no candidates"
        feedback = f"the previous answer was rejected: {last_error}"
    return report
