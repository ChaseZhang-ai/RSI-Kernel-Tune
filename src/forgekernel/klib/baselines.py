"""Baseline candidates generated from a problem's ``definition.json``.

A definition holds the reference implementation (a Python source string defining ``run``), the
inputs and outputs with their shapes and dtypes, and the axes. From it this module generates
starting points that need no kernel work at all — the "the library already has an operator for
this" family:

* ``ref`` — the reference implementation itself, wrapped so it follows the submission contract
  (positional ``run(*args)``, pre-allocated outputs last copied into, otherwise returned).
* ``compile-default`` / ``compile-max-autotune`` / ``compile-reduce-overhead`` — the same,
  through ``torch.compile(mode=...)``, falling back to the eager reference if compilation
  raises.
* each of the four also with a tensor-core precision variant: ``allow_tf32`` and
  ``set_float32_matmul_precision("high")`` set around the call and **restored in a ``finally``**
  (background doc §5) — the global flags never outlive ``run()``.

Everything here is pure text generation: no GPU, no torch import at generation time. The
optional ``--rewrite`` path asks one teacher turn for library-operator candidates and validates
its answer (JSON only, the prompt is ``meta/baseline_rewrite_prompt.md``).
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from forgekernel.klib import normalize as nz

#: The four wrappers every definition gets, before the precision variants.
COMPILE_MODES = (None, "default", "max-autotune", "reduce-overhead")

REWRITE_PROMPT_FILE = "meta/baseline_rewrite_prompt.md"


@dataclass
class Candidate:
    """One generated baseline: a name, a complete single-file source, and what it uses."""

    name: str
    source: str
    uses: str = ""
    precision: str = "default"        # default | tf32
    compile_mode: str | None = None
    kind: str = "mechanical"          # mechanical | rewrite
    preconditions: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def __post_init__(self) -> None:
        # Every candidate must parse and must define `run`; fail at generation, not at import.
        nz.parse(self.source, f"{self.name}.py")
        if "run" not in nz.top_level_functions(self.source):
            raise nz.NormalizeError(f"{self.name}: generated source has no top-level run")


def signature(definition: dict) -> tuple[list[str], list[str]]:
    """``(input names, output names)`` in the definition's order."""
    return list((definition.get("inputs") or {})), list((definition.get("outputs") or {}))


def warmstart_violations(source: str, *, n_inputs: int | None = None,
                         n_outputs: int | None = None) -> list[str]:
    """Task warmstart's entry validation, when that module exists (soft dependency).

    The contract this calls is ``forgekernel.warmstart.validate.validate_source(source,
    n_inputs=…, n_outputs=…)`` returning the violations (``[]`` = valid); a version that takes
    only the source is accepted too. A module that is absent, or that answers with an
    unexpected type, is not an error: the syntax/entry check the caller already did stands
    (background doc §12: warmstart is a soft dependency of the library).
    """
    try:
        from forgekernel.warmstart.validate import validate_source
    except Exception:  # noqa: BLE001 -- absent or still being written by its task
        return []
    try:
        result = validate_source(source, n_inputs=n_inputs, n_outputs=n_outputs)
    except TypeError:
        try:
            result = validate_source(source)
        except Exception:  # noqa: BLE001
            return []
    except Exception:  # noqa: BLE001
        return []
    if result is None or isinstance(result, bool):
        return [] if result in (None, True) else ["warmstart.validate rejected the candidate"]
    if isinstance(result, (list, tuple)):
        return [str(x) for x in result]
    return []


def reference_source(definition: dict) -> str:
    """The definition's reference implementation (a Python source string)."""
    reference = definition.get("reference")
    if not isinstance(reference, str) or not reference.strip():
        raise nz.NormalizeError("the definition has no `reference` source")
    if "run" not in nz.top_level_functions(reference):
        raise nz.NormalizeError("the reference does not define a top-level `run`")
    return reference


def _spec_lines(specs: dict) -> list[str]:
    lines = []
    for name, spec in specs.items():
        if not isinstance(spec, dict):
            lines.append(f"#   {name}: <scalar>")
            continue
        lines.append(f"#   {name}: shape={spec.get('shape')} dtype={spec.get('dtype')}")
    return lines


_TEMPLATE = '''"""{name} — generated by `forge lib baselines` from a problem definition.

What it is: {uses}
Wrapper: {wrapper}
Inputs (positional, in this order):
{input_lines}
Outputs (pre-allocated and passed last when the harness uses destination-passing style;
otherwise `run` returns them, in this order):
{output_lines}
The reference implementation follows verbatim; only its top-level `run` was renamed.
"""
import torch

{impl_helpers}

# ---- reference implementation ------------------------------------------------
{reference}


_N_INPUTS = {n_inputs}
_N_OUTPUTS = {n_outputs}
_OUTPUT_NAMES = {output_names}


def _klib_copy_outputs(result, outs):
    """Copy a return value into the pre-allocated outputs (DPS), or return it."""
    if result is None:
        return None
    if isinstance(result, dict):
        for name, dst in zip(_OUTPUT_NAMES, outs):
            dst.copy_(result[name])
    elif isinstance(result, (tuple, list)):
        for dst, value in zip(outs, result):
            dst.copy_(value)
    else:
        outs[0].copy_(result)
    return None


{dispatch}

{precision_helper}

def run(*args):
    """Positional call; when outputs are passed last they are written in place."""
    if len(args) > _N_INPUTS:
        outs = args[_N_INPUTS:]
        result = {call}
        return _klib_copy_outputs(result, outs)
    return {call_plain}
'''

_PRECISION_HELPER = '''def _klib_call_with_flags(torch, fn, args):
    """Run `fn(*args)` with tensor-core precision knobs, restoring them in a `finally`."""
    previous_allow_tf32 = torch.backends.cuda.matmul.allow_tf32
    previous_precision = torch.get_float32_matmul_precision()
    torch.backends.cuda.matmul.allow_tf32 = True
    torch.set_float32_matmul_precision("high")
    try:
        return fn(*args)
    finally:
        torch.backends.cuda.matmul.allow_tf32 = previous_allow_tf32
        torch.set_float32_matmul_precision(previous_precision)
'''

_DISPATCH_PLAIN = '''def _klib_dispatch(*args):
    return _klib_ref(*args)
'''

_DISPATCH_COMPILED = '''def _klib_make_impl():
    try:
        return torch.compile(_klib_ref, mode={mode!r})
    except Exception:
        return _klib_ref


_KLIB_IMPL = _klib_make_impl()


def _klib_dispatch(*args):
    try:
        return _KLIB_IMPL(*args)
    except Exception:
        return _klib_ref(*args)
'''


def _candidate_name(compile_mode: str | None, precision: str) -> str:
    base = "ref" if compile_mode is None else f"compile-{compile_mode}"
    return base if precision == "default" else f"{base}-tf32"


def _render(name: str, definition: dict, reference: str, *, compile_mode: str | None,
            precision: str) -> Candidate:
    inputs, outputs = signature(definition)
    uses = ("the reference implementation" if compile_mode is None
            else f"torch.compile(mode={compile_mode!r}) around the reference implementation")
    if precision == "tf32":
        uses += " with TF32 / high float32 matmul precision (restored after each call)"
    wrapper = ("torch.compile, eager fallback on any exception" if compile_mode is not None
               else "eager")
    if precision == "tf32":
        wrapper += "; precision flags restored in a finally"
    dispatch = (_DISPATCH_PLAIN if compile_mode is None
                else _DISPATCH_COMPILED.format(mode=compile_mode))
    call = ("_klib_call_with_flags(torch, _klib_dispatch, args[:_N_INPUTS])"
            if precision == "tf32" else "_klib_dispatch(*args[:_N_INPUTS])")
    call_plain = ("_klib_call_with_flags(torch, _klib_dispatch, args)"
                  if precision == "tf32" else "_klib_dispatch(*args)")
    source = _TEMPLATE.format(
        name=name,
        uses=uses,
        wrapper=wrapper,
        input_lines="\n".join(_spec_lines(definition.get("inputs") or {})),
        output_lines="\n".join(_spec_lines(definition.get("outputs") or {})),
        impl_helpers="# ---- implementation and precision helpers ------------------------------",
        reference=reference,
        n_inputs=len(inputs),
        n_outputs=len(outputs),
        output_names=repr(outputs),
        dispatch=dispatch,
        precision_helper=(_PRECISION_HELPER if precision == "tf32" else ""),
        call=call,
        call_plain=call_plain,
    )
    notes = []
    if compile_mode is not None:
        notes.append("torch.compile compiles lazily: the first call pays the compile; the "
                     "harness measures that as cold start")
    return Candidate(name=name, source=source, uses=uses, precision=precision,
                     compile_mode=compile_mode, kind="mechanical", notes=notes)


def mechanical_candidates(definition: dict) -> list[Candidate]:
    """The 1 + 3 wrappers × 2 precision variants = 8 candidates of a definition."""
    reference = reference_source(definition)
    renamed = nz.rename_symbol(reference, "run", "_klib_ref")
    inputs, outputs = signature(definition)
    out: list[Candidate] = []
    for compile_mode in COMPILE_MODES:
        for precision in ("default", "tf32"):
            candidate = _render(_candidate_name(compile_mode, precision), definition, renamed,
                                compile_mode=compile_mode, precision=precision)
            problems = warmstart_violations(candidate.source, n_inputs=len(inputs),
                                            n_outputs=len(outputs))
            if problems:
                raise nz.NormalizeError(f"{candidate.name}: warmstart.validate: "
                                        + "; ".join(problems))
            out.append(candidate)
    return out


def write_candidates(out_dir: str | Path, candidates: list[Candidate], *,
                     definition_name: str = "") -> list[Path]:
    """Write ``<out>/<name>.py`` for each candidate (a manifest lists what each uses)."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    manifest = []
    for cand in candidates:
        path = out / f"{cand.name.replace('/', '-')}.py"
        path.write_text(cand.source, encoding="utf-8")
        written.append(path)
        manifest.append({"name": cand.name, "file": path.name, "uses": cand.uses,
                         "kind": cand.kind, "precision": cand.precision,
                         "compile_mode": cand.compile_mode,
                         "preconditions": cand.preconditions, "notes": cand.notes})
    (out / "manifest.json").write_text(
        json.dumps({"definition": definition_name, "candidates": manifest},
                   indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return written


