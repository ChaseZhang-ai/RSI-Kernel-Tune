"""The per-problem reference-implementation fallback for every track.

A track submission scores a missing kernel as 0 and the official guide's shortcut is "submit
the reference implementation" — a correct, unoptimized kernel every problem can have. This
module generates exactly that, one directory per problem, in the collection-submission layout
(background doc §3.1):

    <out>/<problem_name>/submission.py

Each file wraps the definition's reference in the submission contract (positional
``run(*args)``, pre-allocated outputs last copied into, otherwise returned) and tries a
``torch.compile`` fast path first; **any exception falls back to the eager reference**, which
is the implementation the definition guarantees. Nothing else is imported and no file besides
``submission.py`` is needed by the evaluator.

The generated files are a floor, not an optimization: the reference's own latency is what the
board measures, and the board's table shows that score is problem-dependent (some references
sit at 0.16 SOL on their problem). What this guarantees is a *valid* entry for every problem;
the score is whatever the board gives the reference.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable

from forgekernel.klib import baselines as bl
from forgekernel.klib import normalize as nz

SUBMISSION_NAME = "submission.py"
MANIFEST_NAME = "_cover_manifest.json"

_TEMPLATE = '''"""{problem} — the reference implementation as a submission (generated by `forge lib cover`).

This file is the floor for every track submission: correct by construction (it is the
problem's own reference), one file, top-level `run(*args)`, positional arguments. The first
call tries a `torch.compile` copy; any exception falls back to the eager reference, so a
compilation problem can never turn into a wrong or missing answer.
"""
import torch

# ---- reference implementation (verbatim; its top-level `run` was renamed) ----
{reference}


_N_INPUTS = {n_inputs}
_N_OUTPUTS = {n_outputs}
_OUTPUT_NAMES = {output_names}

_COMPILED = None


def _klib_copy_outputs(result, outs):
    if result is None:
        return None
    if isinstance(result, dict):
        for name, dst in zip(_OUTPUT_NAMES, outs):
            dst.copy_(result[name])
    elif isinstance(result, (tuple, list)):
        for dst, value in zip(outs, result):
            dst.copy_(value)
    else:
        outs[0].copy_(result)
    return None


def _klib_fast(*args):
    """The compiled reference, or the eager reference if compilation/execution raises."""
    global _COMPILED
    if _COMPILED is None:
        try:
            _COMPILED = torch.compile(_klib_ref)
        except Exception:
            _COMPILED = _klib_ref
    try:
        return _COMPILED(*args)
    except Exception:
        return _klib_ref(*args)


def run(*args):
    """Positional call; the reference is the fallback that always runs."""
    if len(args) > _N_INPUTS:
        outs = args[_N_INPUTS:]
        try:
            result = _klib_fast(*args[:_N_INPUTS])
        except Exception:
            result = _klib_ref(*args[:_N_INPUTS])
        return _klib_copy_outputs(result, outs)
    try:
        return _klib_fast(*args)
    except Exception:
        return _klib_ref(*args)
'''


@dataclass
class CoverResult:
    problem: str
    subset: str
    path: str = ""
    ok: bool = True
    error: str = ""


@dataclass
class CoverReport:
    out: str
    results: list[CoverResult] = field(default_factory=list)
    skipped: list[dict] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {"out": self.out,
                "written": sum(1 for r in self.results if r.ok),
                "problems": [{"problem": r.problem, "subset": r.subset, "path": r.path,
                              "ok": r.ok, "error": r.error} for r in self.results],
                "skipped": self.skipped}


def _safe_dir_name(name: str) -> bool:
    """The collection layout's directory rule: the name as-is, no separators."""
    return bool(name) and Path(name).name == name and "\\" not in name and not name.startswith(".")


def submission_source(definition: dict, *, problem: str) -> str:
    """The generated ``submission.py`` text for one definition."""
    reference = bl.reference_source(definition)
    renamed = nz.rename_symbol(reference, "run", "_klib_ref")
    inputs, outputs = bl.signature(definition)
    source = _TEMPLATE.format(
        problem=problem,
        reference=renamed,
        n_inputs=len(inputs),
        n_outputs=len(outputs),
        output_names=repr(outputs),
    )
    nz.parse(source, f"{problem}/{SUBMISSION_NAME}")
    if "run" not in nz.top_level_functions(source):
        raise nz.NormalizeError(f"{problem}: generated submission has no top-level run")
    return source


def cover(dataset: str | Path, out: str | Path, *, only: Iterable[str] | None = None) -> CoverReport:
    """Write ``<out>/<problem>/submission.py`` for every problem of the dataset."""
    dataset = Path(dataset)
    out = Path(out)
    report = CoverReport(out=str(out))
    wanted = {str(x) for x in only} if only else None
    for subset_dir in sorted(p for p in dataset.iterdir() if p.is_dir()):
        for problem_dir in sorted(p for p in subset_dir.iterdir() if p.is_dir()):
            definition_path = problem_dir / "definition.json"
            if not definition_path.is_file():
                continue
            name = problem_dir.name
            if wanted is not None and name not in wanted:
                continue
            try:
                definition = json.loads(definition_path.read_text(encoding="utf-8"))
            except (OSError, ValueError) as exc:
                report.skipped.append({"problem": name, "subset": subset_dir.name,
                                       "reason": f"cannot read definition.json: {exc}"})
                continue
            if not _safe_dir_name(name):
                report.skipped.append({"problem": name, "subset": subset_dir.name,
                                       "reason": "not a usable directory name"})
                continue
            try:
                source = submission_source(definition, problem=name)
            except nz.NormalizeError as exc:
                report.results.append(CoverResult(problem=name, subset=subset_dir.name,
                                                  ok=False, error=str(exc)))
                continue
            target = out / name
            target.mkdir(parents=True, exist_ok=True)
            path = target / SUBMISSION_NAME
            path.write_text(source, encoding="utf-8")
            report.results.append(CoverResult(problem=name, subset=subset_dir.name,
                                              path=str(path)))
    out.mkdir(parents=True, exist_ok=True)
    (out / MANIFEST_NAME).write_text(
        json.dumps(report.to_dict(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return report


def verify_layout(out: str | Path) -> list[str]:
    """Problems of the collection layout: one dir per problem, one ``submission.py`` inside."""
    out = Path(out)
    problems: list[str] = []
    if not out.is_dir():
        return problems
    for directory in sorted(p for p in out.iterdir() if p.is_dir()):
        submission = directory / SUBMISSION_NAME
        if not submission.is_file():
            problems.append(f"{directory.name}: no {SUBMISSION_NAME}")
            continue
        try:
            source = submission.read_text(encoding="utf-8")
            nz.parse(source, str(submission))
        except (OSError, nz.NormalizeError) as exc:
            problems.append(f"{directory.name}: {exc}")
            continue
        if "run" not in nz.top_level_functions(source):
            problems.append(f"{directory.name}: no top-level run")
        if not re.search(r"^\s*def run\(.*\*\s*args", source, re.M):
            problems.append(f"{directory.name}: run does not take *args")
        if "try:" not in source or "except Exception" not in source:
            problems.append(f"{directory.name}: no try/except fallback")
    return problems
