"""Card kit: the shared assets every generated card rides on.

The pieces `rsi-kernel-tune run` renders into ``operators/<op>/`` (taskcard.py):

  * ``GPU_ENTRY_TEMPLATE`` -- the job entry script: the clock-lock discipline (locks
    only what the card's ``[protocol]`` asks for, verifies it took, clears it again on
    the way out, and refuses to time without it), the NCU metric filter, the WP11
    merged eval+NCU task and the content-addressed build cache;
  * ``BENCH_TEMPLATE`` / ``NCU_TEMPLATE`` -- the generated eval/bench.py and
    eval/ncu_run.py, which call the card's own bench engine (eval/benchkit.py);
  * the CUDA kernel-file conventions shared with the bench engine's builder.

Pure string templates and small helpers -- no I/O, no torch.
"""

