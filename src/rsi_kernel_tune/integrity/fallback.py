"""A submission that falls back to the definition's reference when the fast path fails.

The last step of an export is the one where a kernel goes to the board alone: on a cold
process, in an image that may differ from the development machine.  A kernel that raises
there scores 0 for the problem; a kernel that raises there and falls back to the
definition's own reference scores 0.5 (the reference is the board's baseline).  So the
final export is wrapped:

    submission.py = wrap_with_fallback(kernel_src, reference_src)

The generated file's top-level ``run(*args)`` calls the fast implementation; **any**
exception -- an initialisation that fails on import, a JIT that cannot compile, a shape it
does not handle, a numerical check inside it -- falls back to the torch reference on the
same positional arguments, and the reference's result is copied into the preallocated
output tensors (the destination-passing-style contract the board uses).

Two things it must not do, and does not:

* **Lose the licence banner.**  ``kernel_src``'s leading comment block (the NOTICE banner
  ``rsi_kernel_tune.integrity.notices.banner`` wrote, and whatever licence header the kernel
  carries) is copied verbatim to the very top of the new file, before anything else.
* **Initialize at import time.**  Both sources are embedded as string constants and
  executed lazily, on the first call to ``run``.  A module-level compile in the kernel
  therefore still happens inside the first call -- and a failure there is caught by the
  same fallback, which is the point.

What it *does* hide: a broken kernel still scores, and the traceback goes to stderr rather
than the board's verdict.  So it is applied at the final export only (campaign's compose),
never during development, and the note it prints names the exception.
"""

from __future__ import annotations

BANNER_MARK = "# NOTICE:"


def leading_comment_block(source: str) -> str:
    """The comment / blank lines a file starts with (a licence header or NOTICE banner)."""
    lines = source.splitlines(True)
    out: list[str] = []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("#") or not stripped:
            out.append(line)
            continue
        break
    while out and not out[-1].strip():
        out.pop()
    return "".join(out)


_GENERATED = '''"""{title}

GENERATED by rsi_kernel_tune.integrity.fallback.wrap_with_fallback -- do not hand-edit.
The fast implementation below is the exported kernel, embedded as source; the fallback is
the definition's own reference.  Every exception -- including one raised while the fast
implementation's module-level code runs -- falls back to the reference.
"""

import sys as _sys

import torch as _torch

_KERNEL_SRC = {kernel!r}
_REFERENCE_SRC = {reference!r}

_KERNEL = None
_REFERENCE = None
_FALLBACK_COUNT = 0
_REPORTED = False


def _load(source, name):
    namespace = {{"__name__": name, "__file__": name + ".py"}}
    exec(compile(source, name + ".py", "exec"), namespace)   # noqa: S102 -- our own source
    return namespace


def _fast_run():
    global _KERNEL
    if _KERNEL is None:
        namespace = _load(_KERNEL_SRC, "_fk_fast")
        run = namespace.get("run")
        if not callable(run):
            raise AttributeError("the fast implementation has no top-level run()")
        _KERNEL = run
    return _KERNEL


def _reference_run():
    global _REFERENCE
    if _REFERENCE is None:
        namespace = _load(_REFERENCE_SRC, "_fk_reference")
        run = namespace.get("run")
        if not callable(run):
            raise AttributeError("the reference has no top-level run()")
        _REFERENCE = run
    return _REFERENCE


def _copy_back(result, args):
    """Write a value-returning reference's tensors into the preallocated outputs."""
    if result is None:
        return
    values = list(result.values()) if isinstance(result, dict) else \\
        (list(result) if isinstance(result, (tuple, list)) else [result])
    values = [v for v in values if _torch.is_tensor(v)]
    if not values:
        return
    slots = [a for a in args if _torch.is_tensor(a)]
    # The board passes the outputs last, in the definition's output order; when there are
    # exactly as many trailing slots as values, they are the outputs.  Otherwise match by
    # shape from the end -- a slot that already holds these values needs no copy.
    tail = slots[-len(values):] if len(slots) >= len(values) else []
    if len(tail) == len(values) and all(
            _torch.is_tensor(v) and _torch.is_tensor(s)
            and tuple(v.shape) == tuple(s.shape) and v.dtype == s.dtype
            for v, s in zip(values, tail)):
        for value, slot in zip(values, tail):
            if slot.data_ptr() != value.data_ptr():
                slot.copy_(value)
        return
    for value in reversed(values):
        for slot in reversed(slots):
            if tuple(slot.shape) == tuple(value.shape) and slot.dtype == value.dtype \\
                    and slot.data_ptr() != value.data_ptr():
                slot.copy_(value)
                break


def _reference_call(args):
    """The reference on the same positional arguments.

    The board's convention is destination-passing: the last arguments are the preallocated
    outputs.  The definition's reference is usually value-returning (it takes only the
    inputs and returns tensors), so the call is cut to the number of positional parameters
    the reference declares; a reference that takes all of them (DPS) is called whole.
    """
    ref = _reference_run()
    try:
        import inspect
        params = list(inspect.signature(ref).parameters.values())
        positional = [p for p in params
                      if p.kind in (p.POSITIONAL_ONLY, p.POSITIONAL_OR_KEYWORD)]
        variadic = any(p.kind == p.VAR_POSITIONAL for p in params)
    except (TypeError, ValueError):
        positional, variadic = [], True
    if not variadic and positional and len(positional) < len(args):
        return ref(*args[:len(positional)])
    return ref(*args)


def run(*args):
    """The fast implementation, then the reference if it raised."""
    global _FALLBACK_COUNT, _REPORTED
    try:
        return _fast_run()(*args)
    except Exception as exc:  # noqa: BLE001 -- any failure falls back by design
        _FALLBACK_COUNT += 1
        if not _REPORTED:
            _REPORTED = True
            print("[integrity] fast implementation failed, using the reference: "
                  + type(exc).__name__ + ": " + str(exc)[:600], file=_sys.stderr)
        _copy_back(_reference_call(args), args)
        return None
'''


def wrap_with_fallback(kernel_src: str, reference_src: str, *,
                       title: str = "submission.py (fast implementation + reference fallback)") -> str:
    """A parseable single-file submission: fast path, reference fallback, banner intact."""
    if not isinstance(kernel_src, str) or not kernel_src.strip():
        raise ValueError("wrap_with_fallback needs the kernel's source")
    if not isinstance(reference_src, str) or not reference_src.strip():
        raise ValueError("wrap_with_fallback needs the reference's source")
    declaration = leading_comment_block(kernel_src)
    body = _GENERATED.format(kernel=kernel_src, reference=reference_src, title=title)
    text = (declaration + "\n" if declaration else "") + body
    compile(text, "<submission>", "exec")        # the result must parse
    return text
