def test_a_lane_flip_in_the_chain_fails_loudly(tmp_path, monkeypatch):
    """The regression tripwire: a child that lost the lane (a wiring bug) is a
    loud failure, never a silent lane change."""
    se = _self_evolve()
    task = _evolve_task(tmp_path, memo=True)
    real_read = se.read_task_toml

    def _drops_protocol(task_dir):
        cfg = real_read(task_dir)
        cfg.pop("protocol", None)
        return cfg

    monkeypatch.setattr(se, "read_task_toml", _drops_protocol)
    with pytest.raises(ValueError, match="changed lanes"):
        se.next_generation(task, {"kernel": "def run(x):\n    return x\n"},
                           tmp_path / "tasks/opmemo-g2", 1.05)


def test_carry_levers_json_is_stamped_with_the_parent_lane(tmp_path):
    se = _self_evolve()
    task = _evolve_task(tmp_path, memo=True)
