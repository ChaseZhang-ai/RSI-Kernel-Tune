    assert len(records) == 1 and records[0].verdict == "KEEP"
    assert records[0].memo_fallback["pass"] is None
    from peregrine_kernel.inner.trajectory import build_digest
    digest = build_digest(records, {"value": 1.9})
    kinds = [f["kind"] for f in digest["flags"]]
    assert "memo_fallback_unknown" in kinds


