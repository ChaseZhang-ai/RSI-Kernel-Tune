CARD_TASK_TOML = ('[task]\nlanguage = "cutedsl"\narch = "sm90"\n'
                  '[reference]\nrun = "reference/run.py:run"\nsource = "reference"\n'
                  '[target]\nratio = 1.2\n')

CHECK = SimpleNamespace(
    definition={
        "inputs": {"x": {"shape": ["m", "n"], "dtype": "float32"},
                   "w": {"shape": ["n"], "dtype": "float32"}},
        "outputs": {"out": {"shape": ["m", "n"], "dtype": "float32"}},
    },
    judge_src="def run(x, w):\n    return x\n",
    groups={},
)


def _card_task(tmp_path: Path, *, memo: bool):
    toml = CARD_TASK_TOML + ("[protocol]\nmemo_lane = true\n" if memo else "")
    d = tmp_path / f"tasks/cardtask{'memo' if memo else 'strict'}"
    d.mkdir(parents=True)
    (d / "task.toml").write_text(toml, encoding="utf-8")
    (d / "description.md").write_text("out = x @ w\n", encoding="utf-8")
    (d / "shapes.json").write_text(
        json.dumps([{"name": "small", "axes": {"m": 128, "n": 64}}]), encoding="utf-8")
    (d / "reference").mkdir()
    (d / "reference" / "run.py").write_text("def run(x, w):\n    return x\n",
                                            encoding="utf-8")
    kb = tmp_path / "kb"
    for kbrel in ("hw_kb/cutedsl/sm90", "hw_kb/cutedsl/sm100"):
        (kb / kbrel).mkdir(parents=True, exist_ok=True)
    return load_task(d, kb_root=kb)


