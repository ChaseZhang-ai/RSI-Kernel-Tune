"""M3: the two-lane contract wired (docs/industrial-lane.md §6).

The MEMO industrial lane is an explicit opt-in (`[protocol] memo_lane = true` in
task.toml -> `PK_MEMO_LANE=1` on the card's jobs): memoization on repeated
content is legal there, the timed reading is service latency over the task's
repeating input stream, and the checks that exist because replay was a cheat
(WP9's fresh_recheck conviction, WP29's replay probe) are off. What is never
off is correctness: the judged protocol is identical in both lanes and the
fresh child still runs, attached as `memo_fallback` — the unseen-input hard
gate. STRICT (the default, absent key) is today's behavior byte for byte, and
the lanes' numbers never share a comparison column.

This file pins, per the §6.8 acceptance table: the task key, the card's stamp
and env line, the benchkit lane gates, the eval-JSON parse, the driver's
records and REVERT path, the digest's lane stamp and mixed-lane refusal, and
the self_evolve inheritance/carry guard. Runs on CPU; the GPU parent
rehearsals are pasted in CHANGES-M3.md.
"""

