"""Load the curated SOL-ExecBench / FlashInfer-Bench dataset into planning objects.

``data/sol_execbench_b200_flashinfer.json`` is generated by ``scripts/fetch_board.py``
from the board's public API.  It stores, per kernel: the per-workload ``T_b`` and
``T_SOL`` (sufficient to compute any score), and the published per-kernel scores of
ForgeKernel, Golden Bridge and the best public submission.

The current per-workload *candidate* latencies of a submission are not public, so
``build_specs`` reconstructs a faithful stand-in: every workload of a kernel is placed
at the latency that yields that kernel's **published** score.  This is exact for the
quantity the planner uses (the per-kernel score) and keeps the model honest about what
is known and what is assumed.

Where the published **Fast_1 miss count** is known (ForgeKernel / Golden Bridge), the
reconstruction is split so the count is honoured: ``m`` workloads are placed at a
"straggler" score just below the baseline (``STRAGGLER_SCORE``) and the remaining
``n - m`` at whatever score makes the kernel geometric mean equal the published one.
The board does not say *which* workloads miss, so stragglers are assigned to the largest
``T_b`` workloads; that choice is a documented assumption, not data.
"""

from __future__ import annotations

import json
import math
import re
from dataclasses import dataclass, field
from typing import Dict, Iterable, List, Mapping, Optional, Sequence

from . import objective, portfolio
from .allocator import DEFAULT_RATE, KernelState, WorkloadState
from .curriculum import TaskSpec

STRAGGLER_SCORE = 0.45   # a workload that is not Fast_1 sits just below the baseline


_DEFAULT_ARCH_BRIEFS = {
    "cta-per-tile": 0.35,
    "persistent-cta": 0.65,
    "warp-specialized": 0.85,
    "split-k": 0.55,
    "register-resident": 0.75,
    "fused-epilogue": 0.60,
}


def infer_op_class(name: str) -> str:
    n = name.lower()
    if "gemm" in n:
        return "fp8_gemm" if "fp8" in n or "fp4" in n else "gemm"
    if "moe" in n:
        return "moe"
    if "mla" in n or "gqa" in n or "attention" in n or "attn" in n:
        return "attention"
    if "rmsnorm" in n or "norm" in n:
        return "rmsnorm"
    if "gd n" in n or "gdn" in n or "kda" in n:
        return "linear_attention"
    return "attention"


def load(path: str) -> dict:
    with open(path, "r", encoding="utf-8") as fh:
        ds = json.load(fh)
    if "kernels" not in ds:
        raise ValueError(f"{path}: missing 'kernels'")
    return ds


def kernel_names(ds: Mapping) -> List[str]:
    return sorted(ds["kernels"].keys())


def _score_of(entry: Mapping, which: str) -> Optional[float]:
    scores = entry.get("scores", {})
    val = scores.get(which)
    return float(val) if val is not None else None


def build_specs(
    ds: Mapping,
    current: str = "forgekernel",
    rate: float = DEFAULT_RATE,
    architectures: Optional[Sequence[str]] = None,
    family_rate_scale: Optional[Mapping[str, float]] = None,
    honor_fast1: bool = True,
) -> List[TaskSpec]:
    """Turn the dataset into ``TaskSpec`` objects for planning/mock campaigns.

    ``current`` selects whose score seeds the starting latency: ``forgekernel``,
    ``golden_bridge`` or ``best``.  When ``honor_fast1`` and the published Fast_1 miss
    count is available for ``current``, the reconstruction places that many workloads
    just below the baseline so Fast_1 counts are faithful.
    """
    specs: List[TaskSpec] = []
    for name in kernel_names(ds):
        entry = ds["kernels"][name]
        s = _score_of(entry, current)
        if s is None or s <= 0.0:
            continue
        raw = entry["workloads"]
        n = len(raw)
        # per-workload target score (uniform unless Fast_1 misses are honoured)
        scores = [min(s, 1.0)] * n
        miss = None
        if honor_fast1:
            miss = (entry.get("fast1", {}) or {}).get(f"{current}_missing")
        if miss and 0 < int(miss) < n:
            m = int(miss)
            # order by descending T_b; assign the m largest-workload entries the straggler score
            order = sorted(range(n), key=lambda i: raw[i]["t_b_ms"], reverse=True)
            log_num = n * math.log(s) - m * math.log(STRAGGLER_SCORE)
            sf = math.exp(log_num / (n - m))
            sf = min(1.0, max(1e-6, sf))
            for rank, i in enumerate(order):
                scores[i] = STRAGGLER_SCORE if rank < m else sf

        workloads = []
        for w, sc in zip(raw, scores):
            t_b = float(w["t_b_ms"])
            t_sol = float(w["t_sol_ms"])
            lat = objective.latency_for_score(sc, t_b, t_sol)
            workloads.append(WorkloadState(t_ms=lat, t_b_ms=t_b, t_sol_ms=t_sol, rate=rate))
        op_class = entry.get("op_class") or infer_op_class(name)
        if family_rate_scale:
            for key, scale in family_rate_scale.items():
                if key in name:
                    for w in workloads:
                        w.rate = rate * scale
        archs = list(architectures) if architectures else [
            f"{name}/{suffix}" for suffix in _DEFAULT_ARCH_BRIEFS
        ]
        specs.append(TaskSpec(
            name=name,
            state=KernelState(name=name, workloads=workloads),
            architectures=archs,
            op_class=op_class,
        ))
    return specs


def specs_to_kernel_states(specs: Sequence[TaskSpec]) -> List[KernelState]:
    return [s.state for s in specs]


def published_scores(ds: Mapping, which: str = "forgekernel") -> Dict[str, float]:
    out: Dict[str, float] = {}
    for name in kernel_names(ds):
        s = _score_of(ds["kernels"][name], which)
        if s is not None:
            out[name] = s
    return out


def collection_score_of(ds: Mapping, which: str = "forgekernel") -> float:
    scores = published_scores(ds, which)
    return sum(scores.values()) / len(scores)


def headroom_table(ds: Mapping, which: str = "forgekernel") -> List[dict]:
    """Per kernel: published score, best-known score, gap, and Fast1 bookkeeping."""
    rows = []
    for name in kernel_names(ds):
        e = ds["kernels"][name]
        cur = _score_of(e, which)
        best = _score_of(e, "best")
        gb = _score_of(e, "golden_bridge")
        fast = e.get("fast1", {})
        rows.append({
            "kernel": name,
            "score": cur,
            "best_known": best,
            "golden_bridge": gb,
            "headroom": None if cur is None else 1.0 - cur,
            "delta_to_best": None if (cur is None or best is None) else best - cur,
            "fast1_missing": fast.get(which + "_missing"),
        })
    rows.sort(key=lambda r: (r["headroom"] if r["headroom"] is not None else -1), reverse=True)
    return rows
